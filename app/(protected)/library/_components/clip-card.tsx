function formatTime(s: number): string {
  const m = Math.floor(s / 60)
  const sec = Math.floor(s % 60)
  return `${m}:${sec.toString().padStart(2, "0")}`
}

export interface LibraryClip {
  endSeconds: number
  file: FileItem
  id: number
  note: string | null
  renderStatus: string | null
  startSeconds: number
}

export function ClipsPanel({ clips }: { clips: LibraryClip[] }) {
  // Initial status comes from the server (clip.renderStatus) so a clip never
  // paints before its status is known — no first-load flash. Polling only
  // *updates* the ones still rendering; ready clips drop out and are never
  // re-fetched (so a clip you're watching is never interrupted).
  const [updates, setUpdates] = useState<Record<number, string>>({})
  // Which clip's dialog is open — URL-driven (`?clip=<id>`) so the render-
  // progress card's "View" can deep-link a clip open, and so prev/next mirrors
  // the file browser's `?fileId`.
  const [openId, setOpenId] = useQueryState(
    "clip",
    parseAsInteger.withOptions({ history: "push" })
  )

  const statusOf = (c: LibraryClip) =>
    updates[c.id] ?? c.renderStatus ?? "pending"

  const pendingIds = useMemo(
    () =>
      clips
        .filter(
          (c) => (updates[c.id] ?? c.renderStatus ?? "pending") !== "ready"
        )
        .map((c) => c.id)
        .slice(0, 200),
    [clips, updates]
  )

  const statuses = trpc.clips.renderStatuses.useQuery(
    { clipIds: pendingIds },
    { enabled: pendingIds.length > 0, refetchInterval: 4000 }
  )

  useEffect(() => {
    if (!statuses.data) {
      return
    }
    setUpdates((prev) => {
      const next = { ...prev }
      for (const r of statuses.data) {
        next[r.clipId] = r.status
      }
      return next
    })
  }, [statuses.data])

  return (
    <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-4">
      {clips.map((c, index) => (
        <ClipCard
          clip={c}
          currentIndex={index}
          key={c.id}
          nextId={index < clips.length - 1 ? clips[index + 1].id : null}
          onNavigate={setOpenId}
          onOpenChange={(open) => setOpenId(open ? c.id : null)}
          openId={openId}
          prevId={index > 0 ? clips[index - 1].id : null}
          status={statusOf(c)}
          total={clips.length}
        />
      ))}
    </div>
  )
}

function ClipCard({
  clip,
  status,
  openId,
  currentIndex,
  total,
  prevId,
  nextId,
  onOpenChange,
  onNavigate,
}: {
  clip: LibraryClip
  status: string
  openId: number | null
  currentIndex: number
  total: number
  prevId: number | null
  nextId: number | null
  onOpenChange: (open: boolean) => void
  onNavigate: (id: number) => void
}) {
  const [hovered, setHovered] = useState(false)

  const range = `${formatTime(clip.startSeconds)}–${formatTime(clip.endSeconds)}`
  const ready = status === "ready"

  const bounds = {
    fileId: clip.file.id,
    startSeconds: clip.startSeconds,
    endSeconds: clip.endSeconds,
  }
  // File thumb is the always-present base; the clip's own poster + hover GIF
  // (best-effort, generated by the render job) layer on top once ready. If a
  // preview 404s, the bg-image just shows nothing — the base layer shows
  // through, so there's no broken-image icon.
  const fileThumb = clip.file.r2Key ? getVideoThumbUrl(clip.file.r2Key) : null
  const clipThumb = ready ? getClipThumbUrl(bounds) : null
  const clipGif = ready ? getClipGifUrl(bounds) : null

  const previewLayers = (
    <>
      <div className="absolute inset-0 size-full bg-muted" />
      {fileThumb && (
        <div
          className="absolute inset-0 bg-center bg-cover"
          style={{ backgroundImage: `url(${fileThumb})` }}
        />
      )}
      {clipThumb && (
        <div
          className="absolute inset-0 bg-center bg-cover"
          style={{ backgroundImage: `url(${clipThumb})` }}
        />
      )}
      {clipGif && hovered && (
        <div
          className="absolute inset-0 bg-center bg-cover"
          style={{ backgroundImage: `url(${clipGif})` }}
        />
      )}
    </>
  )

  // Every clip is openable so prev/next can cycle through the whole grid (like
  // the file dialog). Not-yet-ready clips open to their status, not a player.
  return (
    <div className="group relative">
      <MorphingDialog
        onOpenChange={onOpenChange}
        open={openId === clip.id}
        transition={{ type: "spring", stiffness: 200, damping: 24 }}
      >
        <MorphingDialogTrigger className="flex w-full flex-col overflow-hidden border border-border bg-card text-left transition-colors hover:border-ring/40 hover:bg-muted/30">
          {/* biome-ignore lint/a11y/noStaticElementInteractions: hover only swaps in the preview GIF; the trigger itself is the interactive element */}
          {/* biome-ignore lint/a11y/noNoninteractiveElementInteractions: hover preview only, not a control */}
          <div
            className="relative aspect-video bg-black/40"
            onMouseEnter={() => setHovered(true)}
            onMouseLeave={() => setHovered(false)}
          >
            {previewLayers}
            {ready ? (
              <div className="absolute inset-0 flex items-center justify-center bg-gradient-to-t from-black/25 to-transparent">
                <span className="flex size-12 items-center justify-center rounded-full bg-black/50 text-white backdrop-blur-sm">
                  <PlayIcon className="size-6" weight="fill" />
                </span>
              </div>
            ) : (
              <ClipStatusOverlay status={status} />
            )}
          </div>
          <div className="p-2">
            <MorphingDialogTitle className="truncate font-medium text-xs">
              {clip.file.title}
            </MorphingDialogTitle>
            <MorphingDialogSubtitle className="truncate text-[11px] text-muted-foreground tabular-nums">
              {range}
              {clip.note ? ` · ${clip.note}` : ""}
            </MorphingDialogSubtitle>
          </div>
        </MorphingDialogTrigger>

        <ClipDialog
          clip={clip}
          currentIndex={currentIndex}
          nextId={nextId}
          onNavigate={onNavigate}
          prevId={prevId}
          range={range}
          status={status}
          thumb={clipThumb ?? fileThumb}
          total={total}
        />
      </MorphingDialog>
    </div>
  )
}

function ClipDialog({
  clip,
  range,
  thumb,
  status,
  currentIndex,
  total,
  prevId,
  nextId,
  onNavigate,
}: {
  clip: LibraryClip
  range: string
  thumb: string | null
  status: string
  currentIndex: number
  total: number
  prevId: number | null
  nextId: number | null
  onNavigate: (id: number) => void
}) {
  const { isOpen } = useMorphingDialog()
  const file = clip.file
  const ready = status === "ready"

  useDialogArrowKeys(isOpen, prevId, nextId, onNavigate)

  // Fetch the playable/downloadable URL only while open AND ready.
  const playback = trpc.clips.getDownloadUrls.useQuery(
    { clipIds: [clip.id] },
    { enabled: isOpen && ready, staleTime: Number.POSITIVE_INFINITY }
  )
  const url = playback.data?.[0]?.url ?? null
  // Attachment-disposition URL — forces a save instead of opening in a tab.
  const downloadUrl = playback.data?.[0]?.downloadUrl ?? null

  return (
    <MorphingDialogContainer>
      <MorphingDialogContent className="relative max-h-[85vh] w-[90vw] max-w-lg overflow-hidden border border-border bg-card">
        <div className="flex max-h-[85vh] flex-col overflow-hidden">
          <DialogNav
            currentIndex={currentIndex}
            nextId={nextId}
            onNavigate={onNavigate}
            onNavigateCapture={(direction, id) =>
              posthog.capture("clip_dialog_navigated", {
                direction,
                clip_id: id,
              })
            }
            prevId={prevId}
            total={total}
          />

          <div className="relative shrink-0 bg-black">
            {ready && url ? (
              <VideoPlayer active={isOpen} poster={thumb} src={url} />
            ) : (
              // Mirror the player's footprint (aspect-video + the h-11 control
              // bar) so swapping in the video causes no layout shift.
              <div className="bg-black">
                <div className="relative flex aspect-video w-full items-center justify-center">
                  {thumb && (
                    <div
                      className="absolute inset-0 bg-center bg-cover opacity-50"
                      style={{ backgroundImage: `url(${thumb})` }}
                    />
                  )}
                  <ClipDialogMediaStatus ready={ready} status={status} />
                </div>
                <div className="h-11 bg-black/80" />
              </div>
            )}
          </div>

          <div className="min-h-0 flex-1 overflow-y-auto overscroll-contain px-5 pt-5 pb-3">
            <MorphingDialogTitle className="break-words font-semibold text-base leading-snug">
              {file.title}
            </MorphingDialogTitle>

            <MorphingDialogSubtitle className="mt-1.5 flex flex-wrap items-center gap-2">
              {file.agency && (
                <span className="flex items-center gap-1 text-muted-foreground text-xs">
                  <AgencySeal agency={file.agency} />
                  {file.agency}
                </span>
              )}
              <Badge
                className="border-blue-400/30 bg-blue-400/5 font-mono text-[10px] text-blue-400 tracking-tighter"
                variant="outline"
              >
                CLIP
              </Badge>
              <span className="text-[11px] text-muted-foreground tabular-nums">
                {range}
              </span>
            </MorphingDialogSubtitle>

            {(file.incidentDate || file.incidentLocation) && (
              <div className="mt-3 flex flex-wrap gap-x-4 gap-y-1 text-muted-foreground text-xs">
                {file.incidentDate && file.incidentDate !== "N/A" && (
                  <span>
                    <span className="font-medium text-foreground/70">
                      Date:
                    </span>{" "}
                    {file.incidentDate}
                  </span>
                )}
                {file.incidentLocation && file.incidentLocation !== "N/A" && (
                  <span>
                    <span className="font-medium text-foreground/70">
                      Location:
                    </span>{" "}
                    {file.incidentLocation}
                  </span>
                )}
              </div>
            )}

            {clip.note && (
              <p className="mt-3 text-foreground/80 text-sm">{clip.note}</p>
            )}
          </div>

          <div className="flex shrink-0 items-center gap-2 border-border border-t px-5 py-3">
            <a
              aria-disabled={!downloadUrl}
              className={
                downloadUrl ? undefined : "pointer-events-none opacity-50"
              }
              download
              href={downloadUrl ?? "#"}
              onClick={(e) => {
                e.stopPropagation()
                posthog.capture("clip_downloaded", {
                  file_id: file.id,
                  clip_id: clip.id,
                })
              }}
            >
              <Button className="gap-1.5" size="lg" variant="default">
                <DownloadSimpleIcon className="size-4" weight="fill" />
                Download
              </Button>
            </a>
          </div>
        </div>

        <MorphingDialogClose className="text-white/90 drop-shadow-md transition-colors hover:text-white" />
      </MorphingDialogContent>
    </MorphingDialogContainer>
  )
}

/** Media-area placeholder while a clip can't play yet (loading URL, or not
 * rendered). White-on-black to read against the player frame. */
function ClipDialogMediaStatus({
  ready,
  status,
}: {
  ready: boolean
  status: string
}) {
  if (ready) {
    // Ready, but the signed URL is still loading.
    return (
      <div className="relative size-6 animate-spin rounded-full border-2 border-white/30 border-t-white" />
    )
  }
  if (status === "failed") {
    return (
      <div className="relative flex flex-col items-center gap-1.5 text-white">
        <WarningCircleIcon className="size-7" weight="fill" />
        <span className="font-mono text-xs">Render failed</span>
      </div>
    )
  }
  return (
    <div className="relative flex flex-col items-center gap-2 text-white">
      <div className="size-6 animate-spin rounded-full border-2 border-white/30 border-t-white" />
      <span className="font-mono text-xs">
        {status === "processing" ? "Processing…" : "Queued…"}
      </span>
    </div>
  )
}

function ClipStatusOverlay({ status }: { status: string }) {
  if (status === "failed") {
    return (
      <div className="absolute inset-0 z-10 flex flex-col items-center justify-center gap-1.5 bg-black/55 text-white">
        <WarningCircleIcon className="size-6" weight="fill" />
        <span className="font-mono text-[11px]">Render failed</span>
      </div>
    )
  }

  const label = status === "processing" ? "Processing…" : "Queued…"
  return (
    <div className="absolute inset-0 z-10 flex flex-col items-center justify-center gap-2 bg-black/55 text-white">
      <div className="size-6 animate-spin rounded-full border-2 border-white/30 border-t-white" />
      <span className="font-mono text-[11px]">{label}</span>
    </div>
  )
}
